#!/usr/bin/env python3
"""Writes src/tables.rs from SnoizeMIDI's name tables (krevis/MIDIApps, BSD-3).

    gen_tables.py <MIDIApps checkout> > src/tables.rs

"""
import plistlib
import subprocess
import sys
from pathlib import Path

root = Path(sys.argv[1])
lproj = root / "Frameworks/SnoizeMIDI/en.lproj"
rev = subprocess.run(["git", "-C", root, "log", "-1", "--format=%H"],
                     capture_output=True, text=True, check=True).stdout.strip()
cc = plistlib.loads((lproj / "ControllerNames.plist").read_bytes())
mf = plistlib.loads((lproj / "ManufacturerNames.plist").read_bytes())


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = [
    "// Generated by tools/gen_tables.py from SnoizeMIDI's ControllerNames.plist",
    "// and ManufacturerNames.plist, krevis/MIDIApps " + rev + ".",
    "// Copyright (c) 2001-2023, Kurt Revis. BSD-3-Clause; see NOTICE. Do not edit.",
    "",
    "/// Controller names by number; `None` where the table has no name.",
    "pub(crate) static CONTROLLERS: [Option<&str>; 128] = [",
]
for n in range(128):
    name = cc.get(str(n))
    out.append(f"    Some({lit(name)}),  // {n}" if name else f"    None,  // {n}")
out += [
    "];",
    "",
    "/// Manufacturer names, sorted by key: a 1-byte id is its value, a 3-byte id",
    "/// `00 b1 b2` is `0x1_0000 | b1 << 8 | b2`.",
    "pub(crate) static MANUFACTURERS: &[(u32, &str)] = &[",
]
keys = []
for k, name in mf.items():
    b = bytes.fromhex(k)
    key = b[0] if len(b) == 1 else 0x10000 | b[1] << 8 | b[2]
    keys.append((key, name))
for key, name in sorted(keys):
    out.append(f"    (0x{key:05x}, {lit(name)}),")
out.append("];")
print("\n".join(out))
