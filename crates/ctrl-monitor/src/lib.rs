//! The core of the shared MIDI monitor (docs/MONITOR.md).
//!
//! Producers push raw packets into a [`Tap`] without allocating; a
//! [`Collector`] parses them into a bounded [`Store`]; [`describe`] names
//! what the views show.
//!
//! ```
//! use ctrl_monitor::*;
//!
//! let mut store = Store::default();
//! let port = store.port(PortRef::new(PortKind::Alsa, "nanoKEY2:0", "nanoKEY2"));
//! let (mut tap, reader) = tap(TapConfig::default());
//! let mut collector = Collector::new(ParserConfig::default());
//! collector.add(reader);
//!
//! let clock = Clock::new();
//! tap.push(clock.now(), port, Dir::In, &[0x90, 60, 100]);
//! collector.drain(&mut store, clock.now().host_ns);
//!
//! let event = store.events().next().unwrap();
//! let text = describe(&event.msg, None, &Style::default());
//! assert_eq!(text.value, "C4 vel 100");
//! ```

